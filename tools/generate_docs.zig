//! Generate rudel's function docs from Strudel's jsdoc, as its website builds
//! `doc.json` (`npm run jsdoc-json`): the same jsdoc run, config and synonyms
//! plugin over the vendored packages, with the jsdoc-json template.
//!
//! The editor's completion tooltips show what Strudel's autocomplete info panel
//! does (codemirror/autocomplete.mjs `Autocomplete`): description, synonyms,
//! parameters and examples; and entries tagged `superdirtOnly`/`noAutocomplete`
//! are left out of completion, as `hasExcludedTags` leaves them out there.
//!
//! jsdoc itself is a Node program, so Node is still needed to run this:
//!   cd tools/oracle && npm install   (once, for jsdoc and jsdoc-json)
//! Run from the repo root: zig run tools/generate_docs.zig
//! writes crates/rudel-app/src/editor/strudel_docs.rs, a static table.
const std = @import("std");
const Io = std.Io;
const Value = std.json.Value;
const Object = std.json.ObjectMap;

const out_path = "crates/rudel-app/src/editor/strudel_docs.rs";
const doc_json = "target/strudel-doc.json";

const header =
    \\// Generated by tools/generate_docs.zig from Strudel's jsdoc; do not edit.
    \\// SPDX-License-Identifier: AGPL-3.0-or-later
    \\
    \\/// One documented name, as Strudel's `doc.json` describes it.
    \\pub(crate) struct Doc {
    \\    pub(crate) name: &'static str,
    \\    pub(crate) synonyms: &'static [&'static str],
    \\    pub(crate) description: &'static str,
    \\    /// `(name, type, description)`.
    \\    pub(crate) params: &'static [(&'static str, &'static str, &'static str)],
    \\    pub(crate) examples: &'static [&'static str],
    \\    /// Tagged `superdirtOnly` or `noAutocomplete`: not offered in completion.
    \\    pub(crate) excluded: bool,
    \\}
    \\
    \\pub(crate) static DOCS: &[Doc] = &[
    \\
;

var gpa: std.mem.Allocator = undefined; // short-lived tool: the arena is never freed

pub fn main(init: std.process.Init) !void {
    gpa = init.arena.allocator();
    const io = init.io;
    const cwd = Io.Dir.cwd();

    try cwd.createDirPath(io, "target");
    const root = try cwd.realPathFileAlloc(io, ".", gpa);
    const modules = try std.fs.path.join(gpa, &.{ root, "tools", "oracle", "node_modules" });
    var jsdoc = try std.process.spawn(io, .{
        .argv = &.{
            "node",
            try std.fs.path.join(gpa, &.{ modules, "jsdoc", "jsdoc.js" }),
            "packages/",
            "--template",
            try std.fs.path.join(gpa, &.{ modules, "jsdoc-json" }),
            "--destination",
            try std.fs.path.join(gpa, &.{ root, doc_json }),
            "-c",
            "jsdoc/jsdoc.config.json",
        },
        .cwd = .{ .path = "strudel" },
        .stdout = .inherit,
        .stderr = .inherit,
    });
    if (!(try jsdoc.wait(io)).success()) return error.JsdocFailed;

    const json = try cwd.readFileAlloc(io, doc_json, gpa, .limited(256 << 20));
    try cwd.deleteFile(io, doc_json);
    const parsed = try std.json.parseFromSlice(Value, gpa, json, .{});

    var seen: std.StringHashMapUnmanaged(void) = .empty;
    var out: Io.Writer.Allocating = .init(gpa);
    const w = &out.writer;
    try w.writeAll(header);
    var count: usize = 0;
    for (items(parsed.value.object.get("docs"))) |doc_value| {
        const doc = doc_value.object;
        // autocomplete.mjs `isValidDoc`.
        const name = label(doc) orelse continue;
        if (name[0] == '_' or std.mem.eql(u8, str(doc.get("kind")) orelse "", "package")) continue;
        if ((try seen.getOrPut(gpa, name)).found_existing) continue;

        try w.writeAll("    Doc {\n        name: ");
        try rust(w, name);
        try w.writeAll(",\n        synonyms: ");
        try list(w, items(doc.get("synonyms")));
        try w.writeAll(",\n        description: ");
        try rust(w, try text(str(doc.get("description")) orelse ""));
        try w.writeAll(",\n        params: &[");
        for (items(doc.get("params")), 0..) |param, i| {
            const p = param.object;
            try w.writeAll(if (i == 0) "(" else ", (");
            try rust(w, str(p.get("name")) orelse "");
            try w.writeAll(", ");
            try rust(w, try typeNames(p));
            try w.writeAll(", ");
            try rust(w, try text(str(p.get("description")) orelse ""));
            try w.writeByte(')');
        }
        try w.writeAll("],\n        examples: ");
        try list(w, items(doc.get("examples")));
        try w.print(",\n        excluded: {},\n    }},\n", .{excluded(doc)});
        count += 1;
    }
    try w.writeAll("];\n");

    try cwd.writeFile(io, .{ .sub_path = out_path, .data = out.written() });
    std.debug.print("wrote {s} ({d} docs)\n", .{ out_path, count });
}

fn str(v: ?Value) ?[]const u8 {
    return switch (v orelse return null) {
        .string => |s| s,
        else => null,
    };
}

fn items(v: ?Value) []const Value {
    return switch (v orelse return &.{}) {
        .array => |a| a.items,
        else => &.{},
    };
}

/// `doc.name || doc.longname`.
fn label(doc: Object) ?[]const u8 {
    for ([_][]const u8{ "name", "longname" }) |key| {
        if (str(doc.get(key))) |s| if (s.len != 0) return s;
    }
    return null;
}

/// autocomplete.mjs `hasExcludedTags`.
fn excluded(doc: Object) bool {
    for (items(doc.get("tags"))) |t| {
        // Some docs carry plain-string tags, which have no `originalTitle`.
        const title = switch (t) {
            .object => |o| str(o.get("originalTitle")) orelse continue,
            else => continue,
        };
        if (std.mem.eql(u8, title, "superdirtOnly") or std.mem.eql(u8, title, "noAutocomplete")) return true;
    }
    return false;
}

fn typeNames(param: Object) ![]const u8 {
    const names = switch (param.get("type") orelse return "") {
        .object => |t| items(t.get("names")),
        else => return "",
    };
    const strs = try gpa.alloc([]const u8, names.len);
    for (names, strs) |n, *s| s.* = n.string;
    return std.mem.join(gpa, " | ", strs);
}

/// A Rust string literal.
fn rust(w: *Io.Writer, s: []const u8) !void {
    try w.writeByte('"');
    for (s) |c| switch (c) {
        '\\' => try w.writeAll("\\\\"),
        '"' => try w.writeAll("\\\""),
        '\r' => {},
        '\n' => try w.writeAll("\\n"),
        else => try w.writeByte(c),
    };
    try w.writeByte('"');
}

fn list(w: *Io.Writer, xs: []const Value) !void {
    try w.writeAll("&[");
    for (xs, 0..) |x, i| {
        if (i != 0) try w.writeAll(", ");
        try rust(w, x.string);
    }
    try w.writeByte(']');
}

/// The HTML jsdoc's markdown plugin produced, as the plain text a tooltip shows.
/// One pass per replacement, in the order the JS regex chain ran them.
fn text(html: []const u8) ![]const u8 {
    var s = try code(html);
    s = try rep(s, "<li>", "• ");
    for ([_][]const u8{ "</p>", "</li>", "</ul>", "</ol>", "</pre>" }) |close| s = try rep(s, close, "\n");
    s = try sub(s, br, "\n");
    s = try sub(s, tag, "");
    s = try rep(s, "&quot;", "\"");
    s = try rep(s, "&#39;", "'");
    s = try rep(s, "&#x27;", "'");
    s = try rep(s, "&lt;", "<");
    s = try rep(s, "&gt;", ">");
    s = try rep(s, "&nbsp;", " ");
    s = try rep(s, "&amp;", "&");
    s = try sub(s, trailingBlanks, "\n");
    s = try sub(s, blankLines, "\n\n");
    // shortcut: ASCII whitespace only, where JS `trim` also strips Unicode
    // spaces; upgrade if a description ever starts or ends with one.
    return std.mem.trim(u8, s, " \t\n\r\x0b\x0c");
}

fn rep(s: []const u8, needle: []const u8, with: []const u8) ![]const u8 {
    return std.mem.replaceOwned(u8, gpa, s, needle, with);
}

/// `<code>([\s\S]*?)</code>` to `` `$1` ``.
fn code(s: []const u8) ![]const u8 {
    const open = "<code>";
    const close = "</code>";
    var out: Io.Writer.Allocating = .init(gpa);
    var rest = s;
    while (std.mem.indexOf(u8, rest, open)) |a| {
        const body = rest[a + open.len ..];
        const b = std.mem.indexOf(u8, body, close) orelse break;
        try out.writer.print("{s}`{s}`", .{ rest[0..a], body[0..b] });
        rest = body[b + close.len ..];
    }
    try out.writer.writeAll(rest);
    return out.written();
}

/// `s` with every match replaced; `match` gives the length matched at the
/// start of its (non-empty) argument, or 0.
fn sub(s: []const u8, match: *const fn ([]const u8) usize, with: []const u8) ![]const u8 {
    var out: Io.Writer.Allocating = .init(gpa);
    var i: usize = 0;
    while (i < s.len) {
        const n = match(s[i..]);
        if (n == 0) {
            try out.writer.writeByte(s[i]);
            i += 1;
        } else {
            try out.writer.writeAll(with);
            i += n;
        }
    }
    return out.written();
}

/// `<br\s*\/?>`
fn br(s: []const u8) usize {
    if (!std.mem.startsWith(u8, s, "<br")) return 0;
    var i: usize = 3;
    while (i < s.len and std.ascii.isWhitespace(s[i])) i += 1;
    if (i < s.len and s[i] == '/') i += 1;
    return if (i < s.len and s[i] == '>') i + 1 else 0;
}

/// `<[^>]+>`
fn tag(s: []const u8) usize {
    if (s[0] != '<') return 0;
    const end = std.mem.indexOfScalar(u8, s, '>') orelse return 0;
    return if (end > 1) end + 1 else 0;
}

/// `[ \t]+\n`
fn trailingBlanks(s: []const u8) usize {
    var i: usize = 0;
    while (i < s.len and (s[i] == ' ' or s[i] == '\t')) i += 1;
    return if (i != 0 and i < s.len and s[i] == '\n') i + 1 else 0;
}

/// `\n{3,}`
fn blankLines(s: []const u8) usize {
    var i: usize = 0;
    while (i < s.len and s[i] == '\n') i += 1;
    return if (i >= 3) i else 0;
}

test text {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    gpa = arena.allocator();
    try std.testing.expectEqualStrings(
        "a `x < y` & \"q\"\n\n• b\n\nc<>", // what the JS chain gives
        try text("<p>a <code>x &lt; y</code> &amp; &quot;q&quot;  </p>\n\n\n<ul><li>b</li></ul><br />c<>"),
    );
}
